"""Generate src/fontMetrics.ts: per-font advance-width ratios for the selectable
menu fonts, so the TV (which can't measure text before laying it out) can
estimate how many lines an item name wraps to in each font.

Reads the .ttf files shipped in the TV app's @expo-google-fonts packages, so the
numbers match exactly what the panel renders. Roboto is not generated here — it
keeps the original browser-measured table in layout.ts so existing displays'
pagination never changes.

Usage (from the repo root, after `pnpm install`):
    pip install fonttools
    python3 packages/contracts/scripts/gen-font-metrics.py
"""
import os
import sys

from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
FONTS_DIR = os.path.join(ROOT, "node_modules", "@expo-google-fonts")
OUT = os.path.join(ROOT, "packages", "contracts", "src", "fontMetrics.ts")

# Must stay in sync with MENU_FONTS in layout.ts (id -> package, file prefix).
# Only the regular (item names) and bold (prices) weights affect wrapping.
FONTS = [
    ("playfair", "playfair-display", "PlayfairDisplay"),
    ("montserrat", "montserrat", "Montserrat"),
    ("oswald", "oswald", "Oswald"),
    ("lora", "lora", "Lora"),
    ("poppins", "poppins", "Poppins"),
    ("lato", "lato", "Lato"),
    ("merriweather", "merriweather", "Merriweather"),
    ("raleway", "raleway", "Raleway"),
    ("opensans", "open-sans", "OpenSans"),
    ("nunito", "nunito", "Nunito"),
    ("cinzel", "cinzel", "Cinzel"),
    ("josefin", "josefin-sans", "JosefinSans"),
    ("barlowcondensed", "barlow-condensed", "BarlowCondensed"),
    ("caveat", "caveat", "Caveat"),
    ("rubik", "rubik", "Rubik"),
]

# Same character set as ROBOTO_RATIO in layout.ts.
CHARS = (
    " !\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~₹"
    "0123456789"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz"
)
RUPEE = "₹"
# A font without a ₹ glyph falls back to the system font (Roboto) for it.
ROBOTO_RUPEE = 0.569


def ratios(path):
    font = TTFont(path)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    out = {}
    for ch in CHARS:
        glyph = cmap.get(ord(ch))
        if glyph is None:
            out[ch] = ROBOTO_RUPEE if ch == RUPEE else 0.6
        else:
            out[ch] = hmtx[glyph][0] / upm
    return out, ord(RUPEE) in cmap


def ttf(pkg, prefix, weight):
    return os.path.join(FONTS_DIR, pkg, weight, f"{prefix}_{weight}.ttf")


def main():
    lines = [
        "// GENERATED by scripts/gen-font-metrics.py from the TV app's font files.",
        "// Do not edit by hand — re-run the script after changing the font list.",
        "",
        "/** Characters covered by each ratio table, in table order. */",
        "export const FONT_METRIC_CHARS = " + _ts_string(CHARS) + ";",
        "",
        "/** Per-font advance-width ratios (glyph width ÷ font size) at the regular",
        " *  weight, plus the bold/regular width factor measured on price text. */",
        "export const FONT_METRICS: Record<string, { ratios: number[]; boldFactor: number }> = {",
    ]
    for fid, pkg, prefix in FONTS:
        reg, has_rupee = ratios(ttf(pkg, prefix, "400Regular"))
        bold, _ = ratios(ttf(pkg, prefix, "700Bold"))
        price = "0123456789" + RUPEE
        bold_factor = sum(bold[c] for c in price) / sum(reg[c] for c in price)
        if not has_rupee:
            print(f"note: {fid} has no ₹ glyph (falls back to Roboto)", file=sys.stderr)
        nums = ", ".join(f"{reg[c]:.3f}".rstrip("0").rstrip(".") for c in CHARS)
        lines.append(f"  {fid}: {{")
        lines.append(f"    boldFactor: {bold_factor:.3f},")
        lines.append(f"    ratios: [{nums}],")
        lines.append("  },")
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


def _ts_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
